-- C. CREDIT SETTLEMENT FUNCTIONS
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.mark_credit_order_paid(p_order_id TEXT)
RETURNS public.orders
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order public.orders;
BEGIN
  SELECT * INTO v_order
  FROM public.orders
  WHERE id::text = p_order_id OR invoice_no = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order % not found', p_order_id;
  END IF;

  UPDATE public.orders
  SET credit_status = 'paid',
      credit_paid_at = NOW(),
      updated_at = NOW()
  WHERE id = v_order.id
  RETURNING * INTO v_order;

  RETURN v_order;
END;
$$;

-- Records HOW the balance was paid (Cash / GPay / Split), validates a split, closes the bill.
CREATE OR REPLACE FUNCTION public.settle_credit_order(
  p_order_id TEXT,
  p_mode     TEXT DEFAULT 'CASH',     -- CASH | GPAY | SPLIT
  p_cash     NUMERIC DEFAULT 0,       -- used when p_mode = 'SPLIT'
  p_gpay     NUMERIC DEFAULT 0        -- used when p_mode = 'SPLIT'
)
RETURNS public.orders
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order   public.orders;
  v_total   NUMERIC;
  v_paid    NUMERIC;
  v_balance NUMERIC;
  v_mode    TEXT := UPPER(COALESCE(NULLIF(p_mode, ''), 'CASH'));
  v_cash    NUMERIC;
  v_gpay    NUMERIC;
BEGIN
  SELECT * INTO v_order
  FROM public.orders
  WHERE id::text = p_order_id OR invoice_no = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order % not found', p_order_id;
  END IF;

  IF v_mode NOT IN ('CASH', 'GPAY', 'SPLIT') THEN
    RAISE EXCEPTION 'Invalid payment mode %', p_mode;
  END IF;

  v_total   := COALESCE(NULLIF(v_order.total, 0), v_order.grand_total, 0);
  v_paid    := COALESCE(v_order.amount_paid, 0);
  v_balance := GREATEST(0, ROUND(v_total - v_paid, 2));

  IF v_mode = 'SPLIT' THEN
    v_cash := COALESCE(p_cash, 0);
    v_gpay := COALESCE(p_gpay, 0);
    IF ABS(v_cash + v_gpay - v_balance) > 0.009 THEN
      RAISE EXCEPTION 'Split amounts (% + %) must add up to the balance due (%)', v_cash, v_gpay, v_balance;
    END IF;
  ELSIF v_mode = 'GPAY' THEN
    v_cash := 0;
    v_gpay := v_balance;
  ELSE
    v_cash := v_balance;
    v_gpay := 0;
  END IF;

  UPDATE public.orders
  SET status         = 'COMPLETED',
      credit_status  = 'paid',
      balance_due    = 0,
      amount_paid    = v_total,
      cash_received  = v_total,
      credit_paid_at = NOW(),
      split_details  = COALESCE(split_details, '{}'::jsonb)
                       || jsonb_build_object(
                            'settle',
                            jsonb_build_object(
                              'mode',   v_mode,
                              'cash',   v_cash,
                              'gpay',   v_gpay,
                              'amount', v_balance,
                              'at',     to_char(NOW() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
                            )
                          ),
      updated_at     = NOW()
  WHERE id = v_order.id
  RETURNING * INTO v_order;

  RETURN v_order;
END;
$$;


-- ----------------------------------------------------------------------------
-- D. PERMISSIONS (the app uses the public anon key)
-- ----------------------------------------------------------------------------
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO anon, authenticated;

DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'store_settings', 'categories', 'products', 'inventory', 'inventory_logs', 'coupons',
    'expense_categories', 'expenses', 'staff', 'attendance', 'jobs', 'job_assignments',
    'customers', 'orders', 'order_items', 'advance_orders',
    'measurement_orders', 'measurement_options'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "Allow all" ON public.%I', t);
    EXECUTE format(
      'CREATE POLICY "Allow all" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)', t
    );
  END LOOP;
END $$;


-- ----------------------------------------------------------------------------
-- E. LIVE UPDATES (realtime) for attendance and work allocation screens
-- ----------------------------------------------------------------------------
DO $$
DECLARE
  t TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    FOREACH t IN ARRAY ARRAY['attendance', 'jobs', 'staff', 'job_assignments'] LOOP
      IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t
      ) THEN
        EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
      END IF;
    END LOOP;
  END IF;
END $$;


