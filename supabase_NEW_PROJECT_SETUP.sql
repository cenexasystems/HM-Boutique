-- ============================================================================
-- HM BOUTIQUE - COMPLETE DATABASE SETUP FOR A NEW SUPABASE PROJECT
--
-- How to use
--   1. Supabase dashboard -> SQL Editor -> New query
--   2. Paste this whole file and press Run (run it once; it is safe to run again)
--   3. Put the project URL and anon key in your app's environment variables
--
-- What it creates (everything the app reads or writes)
--   A. Shared helpers
--   B. Tables: shop settings, categories, products, inventory + stock log, coupons,
--      expense categories + expenses, staff, attendance, jobs + work assignments,
--      orders + order items, advance orders, customers, measurements
--   C. Credit settlement functions
--   D. Permissions (the app talks to the database with the public anon key)
--   E. Live-update (realtime) for attendance and work allocation
--   F. Indexes
--   G. Starter data: shop profile, course categories, expense categories, course catalogue
--
-- Extra order details are stored inside orders.split_details (jsonb):
--   { cash, gpay, gst_percentage, tax_mode, manual_discount, coupon_discount,
--     advance_paid, advance_mode, advance_cash, advance_gpay,
--     settle: { mode, cash, gpay, amount, at } }
--
-- SECURITY NOTE: the app uses the public anon key from the browser and protects the screens
-- with a passcode, so the policies below allow the anon role full access, exactly like the
-- app expects. Anyone holding your anon key can read/write these tables. Keep the key out of
-- public places you do not need it in, and never put the service_role key in the app.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- A. SHARED HELPERS
-- ----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE OR REPLACE FUNCTION public.refresh_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


